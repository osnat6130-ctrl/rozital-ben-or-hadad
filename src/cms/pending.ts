const uploaded = new Map<string, string>();

/** נקרא מיד אחרי העלאה מוצלחת, לפני שהתוכן מצביע לנתיב החדש */
export function rememberUpload(publicPath: string, localUrl: string) {
  if (publicPath) uploaded.set(publicPath, localUrl);
}

/** הכתובת המקומית של קובץ שהועלה בסשן הזה, אם יש */
export function pendingUpload(publicPath: string): string | undefined {
  return uploaded.get(publicPath);
}
